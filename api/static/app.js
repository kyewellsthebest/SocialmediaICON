(async function boot() {
  const theme = localStorage.getItem("clipengine.theme");
  if (theme) document.documentElement.dataset.theme = theme;

  try {
    const data = await api("/overview");
    setEnvLabel(data);
    showGate(false);
    route();
    setInterval(async () => {
      try { setBadge((await api("/review/queue")).length); } catch { /* ignore */ }
    }, 60000);
  } catch {
    showGate(true);
  }
})();
